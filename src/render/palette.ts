/**
 * 调色板 —— 全项目**唯一**的颜色真相。
 *
 * 两个消费者：`render/scene.ts` 建材质；`render/probe.ts` 做像素分类。
 * 之所以必须共用一份：探针若自己留一套期望色，材质改色之后探针照样"通过"，
 * 于是它就从回归防线退化成了一句安慰 —— 那种测试比没有更坏。
 *
 * ## 这一版为什么是浅色（用户拍板的）
 *
 * 上一版是深蓝科技风（"因为我们的创意与芯片、科技有关"）。用户要求概念验证阶段
 * 换成**极简配色**，参考 `doc/rendering-styles/` 里的三张截图。三张图的共同语言：
 *
 * - **纯色平涂**、无贴图、无渐变；
 * - **中性浅底**（不是深色夜空）；
 * - 立方体靠**顶面/侧面的明度差**读出体积，而不是靠描边或贴图；
 * - 低饱和配色 + 一两个重音色（陶土红、暖黄）。
 *
 * 具体取值来源：
 * - `bg / shell / edge`：参照图 3（等距小城）的浅灰路面与天空。
 * - `brick / hard`：参照图 3 的米白建筑；硬砖压暗一档，保证"可挖 / 不可挖"一眼可分。
 * - `bar`：参照图 3 的陶土红（重音）。
 * - `prize`：参照图 2（CAT 压路机）的工业暖黄（重音）。
 * - `exit`：参照图 3 的鼠尾草绿。
 * - `water`：参照图 3 的浅青遮阳篷色 —— 但**颜色被压深了**，见下方"第二版修订"。
 *
 * ## 第二版修订：用户审图后的三处返工（2026-09）
 *
 * 第一版渲染出来后用户**认可构图**（折痕朝向、取景比例、角色大小），但指出三个观感缺陷。
 * 本版只针对这三点，**没有动布局与几何**：
 *
 * 1. **"配色偏闷"。** 第一版的像素直方图显示主导色全挤在 `#88`–`#b0` 这一段暖灰里
 *    （`#888878` 177k、`#909080` 174k、`#b0a890` 108k、`#888070` 103k），
 *    既没有真正的亮端也没有暗端，已有的一红一黄两个重音全被埋掉。
 *    **对策不是加新颜色，而是把中性家族的明度范围拉开**：`brick` 提到约 228（亮端）、
 *    `hard` 压到约 95（暗端）、`seam` 与 `lad` 一起压深。这样 `bar`（陶土红）与
 *    `prize`（暖金）**原有的饱和度**才浮得出来 —— 重音色一个都没改。
 * 2. **"HUD 深色面板抢主体"** —— 见 `index.html`，本表不涉及。
 * 3. **"岛相对水偏大"** —— 岛是用户指定的 4×4，**不缩岛**；改的是让水面读起来更大
 *    （见 `scene.ts` 的 `waterFar`/`waterNear`）。本表配合调整的是 `water`：
 *    原先 0xa8c6ca 是浅青，明度与暖灰家族太近，读起来像"另一块墙"而不是另一种材质；
 *    现在压到 0x86a3ae 并减青味，让水面明确成为画面的**底**。
 *
 * 之所以只动中性色、一个重音都不碰：`player` / `bar` / `chip` / `exit` / `prize`
 * 同时也是 `probe.ts` 的分类锚点（硬约束 1）。不动它们，改色就不可能破坏探针。
 *
 * ## 两条改色时必须同时满足的硬约束
 *
 * 1. **`probe.ts` 的规则是这份表的另一半契约。** 改 `player` / `bar` / `chip` /
 *    `exit` / `prize` 中的任何一个，都必须同步改 `FEATURE_RULES` 里对应的那条，
 *    否则探针会开始误判（它就不再是回归防线了）。
 * 2. **大面积颜色不要越过每通道 240。** `probe.ts` 把 `r,g,b > 240` 记作"白"，
 *    `tools/probe.mjs` 断言 `whiteRatio < 0.05` —— 那是"整片白块"这类 bug 的探测器。
 *    浅色底本身没问题（本表最亮的底色是 0xeceae4 = 236），但别选到 0xf8f8f8 那一档。
 */
