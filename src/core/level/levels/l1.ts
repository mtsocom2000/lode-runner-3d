/**
 * **L1「折角」** —— 教学关（T14）。每面 **10 列 × 12 行**（整张 20×12，6 层砖）。
 *
 * ## 规模演进（三次都是用户试玩后提的）
 *
 * 7×10（5 层）→ 10×12（6 层，"做宽 + 再加一层"）→ 本轮：**梯子从 8 把减到 4 把、均匀分布**，
 * **岛台从 4×4 放大到 5×5 并居中**。用户的原话："场景增大了，但是场景利用率变低了……
 * 地块和梯子过于密集……中间的地台和水面的面积也小了，长宽应该和已经扩大的左右侧面相等，
 * 这样地台重新回到两个侧面所围的面积的中间。"
 *
 * ## 岛台的大小与位置**不再由渲染层算**（这是本轮的结构性改动）
 *
 * 原先 `scene.ts` 的 `islandAndJetties` 是拿 `halfExtent(fold)` + 写死的 `JETTY_U = 5`
 * 与 `ISLAND_HALF = 2` **算**出岛台与小道的：于是关卡一放大，房间大了而岛台**纹丝不动**
 * （还是 4×4、还是贴在某一侧），"利用率低"就是这么来的。
 *
 * 现在渲染层**照 `level.deck` 逐格画**、宝物照 `level.treasures` 摆 —— 关卡数据是唯一出处，
 * 于是"看得见"与"走得到"结构上不可能不一致（那类事故本仓库栽过两次：甲板锚点、接头方向）。
 * 想摆多大的岛、岛在哪，改这里的 `deck` 就是。
 *
 * ## 它要教会玩家的四件事（顺序即教学顺序）
 *
 * 1. **走与爬**：面 A 底层走廊 → 爬梯上高台；
 * 2. **跨折痕**：两面墙在折痕处是连通的（本作唯一的新机制）。**刻意不强制** —— 岛台本身
 *    就是第二条通路（两条小道把两面墙接在一起，这是用户的设计），所以折痕是"更快的路"
 *    而不是"唯一的门"；教学靠提示引导，不靠封死别的路。
 * 3. **走小道取宝物**：宝物在岛台正中，必须经小道过去；
 * 4. **用坑对付追兵**：挖穿它脚下的砖让它落坑受困，土长回来时它还在坑里就会被活埋（T12-c/d）。
 *
 * ## 地形为什么长这样
 *
 * - **梯子 4 把：`col 2 / 7 / 12 / 17`**（每面两把，间距 5，关于折痕对称：`2↔17`、`7↔12`）。
 *   三条避开：① 折痕最内列（`9` / `10`）—— 那两列在屏幕上被压在一起，梯子放那儿会糊成一对黑括弧；
 *   ② 两个接头的墙面列（`A:4` / `B:15`）—— 在接点那一格"按接头方向"会优先上小道，梯子若落在
 *   那儿，玩家会以为"按上能爬"，实际却被带上小道；③ 落水缺口列。
 *   **为什么顶行两端（`col 2` / `col 17`）也是梯子列**：取到宝物后那两列上的闸门会变成梯子，
 *   顶行于是与梯子接上 —— 这就是本关的"通天梯"。
 * - **岛台 5×5 = `x,z ∈ {-6..-2}`**：奇数边长，**中心正好落在整数格 `(-4,-4)`** ——
 *   两片墙围出的区域从墙内表面（`-8.44`）到墙口外表面（`0`），中心 ≈ `-4.22`，于是岛台**居中**。
 *   4×4 那种偶数边长做不到这一点：中心必然压在**两排砖的缝**上。
 * - **两条小道各 2 格**（`x = -8,-7` 与 `z = -8,-7`）：岛缘（`-6.5`）到墙面（`-8.44`）之间
 *   还空 1.94 格 → 正好两块砖，一眼数得出来（这是概念场景定下的"两道读得出来"那条）。
 * - **两个落水缺口在 `r0` 的 `col 3 / col 16`**（对称），离出生点 3 格 —— 中间还夹着一把梯子
 *   （`col 2`），所以玩家"一路按住右键"才会掉进去，正常点按（一次一格）不会。
 *   **缺口列有两条硬约束**（两条都踩过）：
 *   ① 不能是梯子列或接头列；
 *   ② **两侧的邻格都必须可达** —— 接头会吃掉它在 `enterDir` 那个方向的移动，
 *      所以"接头的下一个格子"本身就少一条来路；缺口若再把它与另一侧切断，那一格就**孤立**了
 *      （`col 5/6` 试过，`unreachable` 当场报出来）。
 * - **出口在顶行 `r11` 的 `col 1 / col 18`**，各由两块硬砖封住（`col 0/2` 与 `col 17/19`）。
 *   **取宝前出口真的走不到**（不是"走到了不算过关"），由 `validate` 的 `exitGated` 每次校验。
 * - **无人机在 `B:18,1`**：离出生点 18 格、跨过折痕还有 8 格，出生点因此不会被守尸；
 *   它又慢于玩家（`DRONE_MOVE_TICKS = 16` = 玩家的一半速），给玩家读完 HUD 教学的时间。
 */
