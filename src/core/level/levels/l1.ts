/**
 * **L1「折角」** —— 教学关（T14）。每面 **7 列 × 10 行**（用户裁定的起步规模，§八-3）。
 *
 * ## 它要教会玩家的四件事（顺序即教学顺序）
 *
 * 1. **走与爬**：面 A 底层走廊 → 爬梯上高台；
 * 2. **跨折痕**：两面墙在折痕处是连通的 —— 本作唯一的新机制。
 *    **刻意不强制**：岛台本身就是第二条通路（两条小道把两面墙接在一起，这是用户的设计），
 *    所以折痕是"更快的路"而不是"唯一的门"。教学靠提示引导，不靠封死别的路。
 *    （换句话说：想让它变成必经之路，得先动"两条小道"这条设计，不是改关卡数据能办到的。）
 * 3. **走小道取宝物**：宝物在岛台上，必须经小道过去；
 * 4. **用坑对付追兵**：无人机追过来时，挖穿它脚下的砖让它掉进坑里（自埋 / 困敌）。
 *
 * ## 为什么是 10 行（而不是 6 行）
 *
 * 用户对概念场景的反馈是"场景小了，应该至少有四层地形"。`rows = 10` → 砖行 `r0/r2/r4/r6/r8`
 * = **5 层砖**（≥4 ✓），行走行 `r1/r3/r5/r7/r9`。同屏格数变多，角色与砖块于是自动变小 ——
 * 这是"改尺寸"真正想要的效果，而不是把砖的尺寸常量调小。
 *
 * ## 尺寸一变，哪些数就必须跟着重算（**别手抄，全由 fold 推**）
 *
 * `render/scene.ts` 的岛台与小道是**算出来**的（`halfExtent(fold)` + `JETTY_U = 5`），
 * 所以关卡数据必须与那套推导一致 —— 两边各写一遍必然漂（这正是"看得见却捡不到"的成因）。
 * `fold = 7` 时：
 *
 * | 量 | 推导 | 值 |
 * |---|---|---|
 * | `halfExtent(7)` | `fold - 0.5` | `6.5` |
 * | 岛心 | `-half + JETTY_U` | `-1.5` |
 * | 岛台 4×4 | 砖心 `-3 … 0`（`centre - 1.5 + i`） | `x,z ∈ {-3..0}` |
 * | 小道接的墙面列 | A: `fold-1-u` / B: `fold+u`，`u = JETTY_U` | **`A:1` / `B:12`** |
 * | 小道那一排 | `round(centre - 0.5)` | `x` 或 `z` = `-2` |
 * | 小道长度 | `round((islandEdge - wallFace) / CUBE)` | 2 格：`-5 / -4` |
 * | 宝物格 | `centre + 0.5`（`scene.ts` 就画在那儿） | `(-1, -1)` |
 *
 * ## 地形为什么长这样
 *
 * - **梯子在 `col 2 / 5 / 8 / 11`**，占 `r1..r8`（`r9` 上那两列是闸门或出口）。两个理由：
 *   ① 刻意**避开折痕最内列（`6` / `7`）** —— 那两列在屏幕上被压在一起（见概念关卡那段推导），
 *      梯子放那儿会糊成一对黑括弧；
 *   ② **避开两个接头的墙面列（`A:1` / `B:12`）** —— 在接点那一格，"按接头方向"会**优先上小道**，
 *      于是那一格的横移（A）或上爬（B）被接头吃掉。梯子若正好落在接点列，玩家会以为
 *      "按上能爬"，实际却被带上小道。**这不只是手感问题**：我第一版把梯子放在 `col 1`，
 *      结果底层走廊被切断，`A:2,1 / A:3,1` 按移动规则**永远走不到** ——
 *      而当时的校验用的是静态图，判"全过"（这件事促成了 `rules/reach.ts` 的诞生）。
 * - **两处闸门列同时是梯子列**（`col 2` 与 `col 11`）：取到宝物后它们变成梯子，
 *   顶行于是与 `col 2` / `col 11` 的梯子接上 —— 这就是本关的"通天梯"（与概念关卡同构）。
 * - **两个落水缺口在 `r0` 的 `col 4 / col 9`**（关于折痕对称，`4 ↔ 9`）。它们**不在出生点旁边**：
 *   概念场景吃过这个亏 —— 出生点离缺口只有 2 格，"点一下走两格"就直接送命。
 *   这里从出生点 `A:0,1` 到最近的缺口要横穿 4 格，而且中间有梯子可以上下绕。
 *   顺带一提：这也让 `r1` 被切成三段，三段**各自**由梯子/上层走廊接回主连通块。
 * - **出口在顶行 `r9` 的 `col 3 / col 10`**（镜像对称 `3 ↔ 10`），左右各由硬砖 `=` 封住（T13 的闸门）：
 *   取到宝物后 `openExit` 把这四块换成梯子，顶行才重新连通。**所以出口在拿到宝物前真的走不到** ——
 *   不是"走到了不算过关"。
 * - **无人机在 `B:11,1`**：离出生点很远（跨过折痕还有 4 格），出生点因此不会被守尸；
 *   它的存在是为了教第 4 件事（挖坑困敌），所以放在玩家取到宝物、开始往回走的必经区域。
 *
 * ## 与概念场景的关系
 *
 * 概念场景（9×6、无敌人、纯布景审查）**保留不动**：它的梯子列 `1/6/11/16`、缺口 `2/15`、
 * 小道 `u=5`、接头 `3/14` 是一套互相锁定的推导，改尺寸等于全部重推。
 * L1 是**新的一关**，代价只在"再写一份数据"，而不是推翻已验收的东西。
 */
