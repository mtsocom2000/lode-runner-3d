/**
 * **概念验证关卡**：用户亲自拍板的最简地形。
 *
 * ## 为什么是这几个数（不是随手挑的）
 *
 * 用户的要求：`3-6 行水平等距的砖块，所有砖块都可打洞；每隔 6-8 个砖块一个梯子，
 * 从地面一直通到最顶的砖块`，并且**每个侧面的宽高比要 3:2**。
 *
 * 宽高比这条能反推出整个网格尺寸。设每面宽 W 列、高 H 行，要 W:H = 3:2。
 * 砖行若隔行布置（砖在 `r0 / r2 / r4`…），玩家走在砖的上一行，则：
 *
 * - k 行砖 → 砖行是 0, 2, …, 2(k-1)；
 * - 玩家行走行是 1, 3, …, 2(k-1)+1；
 * - 网格总高 H = 2k（最上面那行走行也要占一行）。
 *
 * 取 k = 3（"3-6 行"里最简的一档）→ **H = 6**，再要 3:2 → **W = 9**，
 * 于是总列数 18、`fold = 9`。每面 9×6 = 3:2，正好。
 *
 * ## 地形本身
 *
 * - `r0` 一层地板（**全是可挖 `X`**，只留两个落水缺口，见下节），`r2`、`r4` 两层满宽平台；
 * - 梯子在第 1、6、11、16 列，占 `r1..r5` —— 从地面一直贯到最顶砖行。
 *   同面内两梯相距 5 格（1→6、11→16），且关于折痕对称（1↔16、6↔11）。
 * - 出口 `E` 在 `r5` 的第 4、13 列，同样关于折痕对称；左右各由一块**闸门硬砖**封住 ——
 *   集齐宝物前走不到，见下节（T13）。
 *
 * ## 梯子为什么是 `1 / 6 / 11 / 16`（两次都是被投影算出来的）
 *
 * 相机的屏幕横轴是 `∝ (z - x) / √2`，而折痕两侧**离折痕同样远**（同为 `u`）的两格，
 * 投影到屏幕上只差 `2(u - 0.56) / √2`。于是：
 *
 * | 梯子列 | 面内间距 | 内侧梯子的 `u` | 屏幕间距 | 结果 |
 * |---|---|---|---|---|
 * | `2 / 8 / 9 / 15` | 6 | 0 | 0（重合在折痕上） | 被压成黑色小括弧 |
 * | `1 / 7 / 10 / 16` | 6 | 1 | **0.62 格** | 两把梯子叠在一起 |
 * | `1 / 6 / 11 / 16` | 5 | 2 | **2.04 格** | 中间露出约半格空隙 |
 *
 * 关键是**内侧那对梯子的 `u`**：`u` 越大，它们离折痕越远、在屏幕上分得越开。
 * 面宽 9 列、每个面放两把梯子时 `u = 8 - 间距`，所以"间距 6"这条要求本身就把 `u`
 * 锁死在 2 以内 —— 取 5 才换得来 2.04 格的间距。
 * 折痕是这个概念唯一的新东西，不能让它被两把梯子糊住（架构文档 §1.3）。
 *
 * ## 梯子为什么占满 `r1..r5`（而不是只占空格）
 *
 * `buildGraph` 的 `climb` 边是**行 ±1，且两端都必须是 `H`** —— 梯子没法跳过一整层平台。
 * 所以梯子列在 `r2`、`r4` 上是 `H`（平台在这里让出 1 格），玩家仍然能从 `r1/r3/r5`
 * 横着走过去（梯格本身是可站立的）。
 *
 * ## 两个落水缺口在哪、以及为什么**不在**最端头
 *
 * 落水途径①需要一个「地板天然断裂处」（见 `core/rules/drown.ts`）：在 `r0` 上挖掉一格，
 * 正上方 `r1` 是可走的，玩家沿墙走过去就会掉出墙体、落到水面。用户拍板"两端各开一块"。
 *
 * **但字面上的"最端头"开不了。** `col 0` 正是出生点 `PLAYER_SPAWN`（`col 0, row 1`）的
 * 支撑砖 —— 在它下面开洞，出生点会直接悬空，`validateLevel` 的 `spawnStandable` 会红。
 * 而关卡关于折痕对称（`col ↔ 17 − col`），`col 17` 的对称伙伴恰好就是 `col 0`，
 * 于是"两端各一块"在这个尺寸下**必然撞上出生点**。
 *
 * 取 **`col 2` 与 `col 15`**：各距端头 2 格、关于折痕对称（`2 ↔ 15`）、避开出生点，
 * 也避开四把梯子（`col 1 / 6 / 11 / 16` —— 在梯子下面开洞会让梯脚悬空，语义上说不通）。
 * 两列的 `r1` 都是 `.`，所以"走过去就掉"这条路径成立：
 *
 * | 缺口 | 走法 | 结果 |
 * |---|---|---|
 * | `col 2`（墙 A 近西端） | `r1 col0 → col1`（梯脚，站得住）`→ col2` | 无支撑 → 落水 |
 * | `col 15`（墙 B 近东端） | `r1 col17 → col16`（梯脚）`→ col15` | 无支撑 → 落水 |
 *
 * ## 出口为什么要被闸门封住（T13）
 *
 * 用户的裁定是**物理门**：集齐宝物之前，出口必须**真的走不到** —— 不是"走到了也不算过关"。
 *
 * 出口在 `r5`（顶行），左右两侧 `c3 / c5`（以及镜像的 `c12 / c14`）本来是 `.`。把这两格换成
 * 硬砖 `=` 就能封死，靠的是 `supportOf` 的第一条判据：
 *
 * ```ts
 * if (!isPassable(here)) return null;   // isSolid = dig | hard → 砖格根本不是可站立格
 * ```
 *
 * 于是闸门格在通行图上**连节点都不是**，出口成了顶行上一个孤立的口袋。而出口自己仍然站得住
 * （`E` 可通行、正下方 `r4` 是实心砖）—— 所以 `exitStandable` 照旧通过，被封住的只是"走过去"。
 *
 * 集齐宝物后 `openExit` 把这 4 格闸门换成**梯子**，`r5` 上就重新有了横向边：
 * `c2 → c3(梯) → c4(出口)`。这就是本关的"通天梯"。
 *
 * **为什么梯长在出口旁边、而不是出口那一列**：出口要站得住就**必须**保留下方实心砖，
 * 而梯不是实心 —— 所以出口自己那一列铺不了梯。这是几何决定的，不是取舍。
 *
 * **闸门必须显式声明**（`gates` 字段），不能靠"哪块砖挨着出口就开哪块"去推 —— 挨着出口的
 * 硬砖也可能只是布景。理由与甲板接头同（见 `deck.ts` 的 `DeckJoint`）。
 *
 * 这条性质由 `validateLevel` 的 `exitGated` 规则**每次校验**（未开不可达 / 已开可达），
 * 而不是靠某个脚本碰巧跑通。
 *
 * ## 这张关卡解决掉的旧病
 *
 * 上一张 `DEV_FOLD`（构图基准）**走不通**：43 个可站立格碎成 **25 个连通分量**，
 * 出生点所在的块只有 **2 格**。原因是 `r0` 地板有 4 处缺口，把 `r1` 走廊切成了独立小段。
 * 这里 `r0` 只在最外两端的**内侧一格**开口，于是 `r1` 仍被梯脚（`col 1` / `col 16`）
 * 挂在梯子上，`r1 / r3 / r5` 三条行走行各自贯通 —— 整张关卡是**一个连通分量**
 * （60 个可站立格；开洞前是 62）。这条性质由 `test/conceptMinimal.test.ts` 钉住，
 * 别再退回碎块。
 *
 * 数据字形：`X` 可挖砖 `=` 硬砖 `.` 空 `H` 梯 `-` 横杆 `G` 宝物 `E` 出口，
 * 行索引 0 = **最底行**。cols 0..8 = 墙 A，cols 9..17 = 墙 B，折痕在 8|9 之间。
 */
